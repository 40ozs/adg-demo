"""Read the hosted ADG demo database with every session forced read-only (ADG-HOSTED-VERIFY-NODEPLOY-01).

Generated by 40ozs/synthetic-enterprise tools/cutover/demo_release.py (templates). The deploy-free
``Hosted verification (ADG demo)`` workflow runs it inside the API image, against ``ADG_DATABASE_URL``::

    python read_only_db.py run -m app.demo_mode --json verify     # Demo Mode verify, read-only
    python read_only_db.py run - < genesee_press_fingerprint.py   # a script on stdin, read-only
    python read_only_db.py state                                  # findings, audit trail, write counters

Every SQLAlchemy connection, sync or async, first runs ``SET SESSION CHARACTERISTICS AS TRANSACTION
READ ONLY``, commits it and checks ``default_transaction_read_only = on``, or the run stops. PostgreSQL
then refuses any INSERT, UPDATE, DELETE, DDL or sequence change in that session. The Supabase session
pooler drops startup options (PGOPTIONS), so the setting is made per session, after connecting.
"""

from __future__ import annotations

import json
import os
import runpy
import sys
import tempfile

import sqlalchemy as sa
from sqlalchemy import event

READ_ONLY = "SET SESSION CHARACTERISTICS AS TRANSACTION READ ONLY"
sessions = 0


@event.listens_for(sa.engine.Engine, "connect")
def _read_only(dbapi_connection, _record) -> None:
    global sessions
    cursor = dbapi_connection.cursor()
    cursor.execute(READ_ONLY)
    cursor.execute("SHOW default_transaction_read_only")
    if cursor.fetchone()[0] != "on":
        raise SystemExit("read_only_db: the session is not read-only; stopping before any query")
    cursor.close()
    dbapi_connection.commit()
    sessions += 1


STATE_SQL = {
    "database": "SELECT current_database()",
    "findings_by_status": "SELECT status, count(*) FROM risk_findings GROUP BY status ORDER BY status",
    "governance_audit_events": "SELECT count(*), md5(coalesce(string_agg(chain_key || ':' || chain_index || ':' || event_id,"
    " ',' ORDER BY chain_key, chain_index), '')) FROM governance_audit_events",
    # Cumulative per-table write counters: a before/after difference names every table any client wrote to.
    "write_counters": "SELECT relname, n_tup_ins, n_tup_upd, n_tup_del FROM pg_stat_user_tables"
    " WHERE schemaname = 'public' ORDER BY relname",
}


def state() -> dict:
    engine = sa.create_engine(sa.engine.make_url(os.environ["ADG_DATABASE_URL"]))
    try:
        with engine.connect() as connection:
            rows = {key: [list(r) for r in connection.execute(sa.text(sql))] for key, sql in STATE_SQL.items()}
            read_only = connection.execute(sa.text("SHOW transaction_read_only")).scalar_one()
    finally:
        engine.dispose()
    count, digest = rows["governance_audit_events"][0]
    return {
        "database": rows["database"][0][0],
        "transaction_read_only": read_only,
        "findings_by_status": {status: n for status, n in rows["findings_by_status"]},
        "governance_audit_events": {"count": count, "trail_md5": digest},
        "write_counters": {name: {"ins": i, "upd": u, "del": d} for name, i, u, d in rows["write_counters"]},
    }


def main(argv: list[str]) -> int:
    # As `python -m` / `python -` would: the working directory (the image's /app/backend, whose vendor/ the
    # projection lock resolves against), not this script's directory, comes first on the import path.
    sys.path[0] = os.getcwd()
    if argv[:1] == ["state"]:
        print(json.dumps(state(), indent=1, sort_keys=True))
    elif argv[:2] == ["run", "-m"] and len(argv) > 2:
        sys.argv = argv[2:]
        runpy.run_module(argv[2], run_name="__main__", alter_sys=True)
    elif argv[:2] == ["run", "-"]:
        with tempfile.NamedTemporaryFile("w", suffix=".py") as script:  # run_path gives it a real __main__ module
            script.write(sys.stdin.read())
            script.flush()
            sys.argv = [script.name]
            runpy.run_path(script.name, run_name="__main__")
    else:
        print(__doc__, file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main(sys.argv[1:]))
    finally:  # also after the wrapped module's own sys.exit
        print(f"read_only_db: {sessions} database session(s) opened, each read-only", file=sys.stderr)
